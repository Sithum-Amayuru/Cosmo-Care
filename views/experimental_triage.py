"""Experimental triage engine demonstration.

This page runs the teammate's rule-based prototype locally. It does not call
Groq, OpenRouter, or any other AI provider.
"""
import streamlit as st

from ui_theme import apply_theme
from modules.mission_backend import AstronautVitals, get_prototype_triage

apply_theme()
st.title("🧪 Experimental Health Triage Engine")
st.warning(
    "UNVALIDATED RESEARCH PROTOTYPE — This engine can produce incorrect or misleading "
    "medical interpretations. It is not a diagnosis, medical clearance, or treatment "
    "recommendation. Do not use its output to make real medical decisions."
)
st.caption(
    "This demonstration uses manually entered or simulated values and a fixed rule-based "
    "algorithm. It runs locally and does not consume Groq or OpenRouter tokens."
)

with st.form("experimental_triage_form"):
    st.subheader("Input observations")
    c1, c2, c3 = st.columns(3)
    with c1:
        astronaut_id = st.text_input("Demo astronaut ID", value="DEMO-001")
        flight_day = st.number_input("Mission day", min_value=1, max_value=2000, value=24)
        heart_rate = st.number_input("Heart rate (bpm)", min_value=20.0, max_value=250.0, value=68.0)
        systolic = st.number_input("Systolic blood pressure (mmHg)", min_value=50.0, max_value=300.0, value=118.0)
    with c2:
        diastolic = st.number_input("Diastolic blood pressure (mmHg)", min_value=30.0, max_value=200.0, value=76.0)
        hrv = st.number_input("HRV RMSSD (ms)", min_value=0.0, max_value=300.0, value=44.0)
        co2 = st.number_input("CO₂ partial pressure (mmHg)", min_value=0.0, max_value=30.0, value=2.6)
        ectopic = st.number_input("Ectopic beats per minute (demo input)", min_value=0, max_value=100, value=0)
    with c3:
        dizzy = st.checkbox("Dizziness reported")
        headache = st.checkbox("Headache reported")
        region = st.selectbox(
            "Body region",
            ["None", "Neck/Trapezius", "Lumbar Spine", "Left Leg", "Right Leg", "Other"],
        )
        symptom = st.selectbox(
            "Symptom category",
            ["None", "Acute Cramp/Spasm", "Generalized Weakness", "Deep Dull Ache", "Post-ARED DOMS"],
        )
        pain = st.slider("Pain score (0–10)", 0, 10, 0)
    run_engine = st.form_submit_button("Run experimental engine", type="primary")

if run_engine:
    if diastolic >= systolic:
        st.error("Please check the blood pressure values: systolic should be greater than diastolic.")
    else:
        vitals = AstronautVitals(
            astronaut_id=astronaut_id.strip() or "DEMO-001",
            flight_day=int(flight_day),
            hr=float(heart_rate),
            sbp=float(systolic),
            dbp=float(diastolic),
            hrv=float(hrv),
            co2=float(co2),
            ectopic=int(ectopic),
            dizzy=bool(dizzy),
            headache=bool(headache),
            region=region,
            symptom=symptom,
            pain=int(pain),
        )
        result = get_prototype_triage(vitals)
        st.session_state["cosmo_experimental_triage_result"] = result

result = st.session_state.get("cosmo_experimental_triage_result")
if result:
    st.divider()
    st.subheader("Prototype output")
    st.error("Do not interpret this result as a real medical diagnosis or risk classification.")
    st.write("**Engine-generated label (unvalidated):**", result["diagnosis"])
    st.write("**Engine status label (unvalidated):**", result["status_level"])
    st.write("**Engine explanation:**", result["explanation"])
    st.write("**Mission-phase assumption:**", result["phase_name"])
    st.write("**Verification text generated by prototype:**", result["verification"])
    st.caption(result["safety_notice"])
    with st.expander("View calculated values"):
        st.json(
            {
                "z_scores": result["z_scores"],
                "hemodynamics": result["hemodynamics"],
            }
        )

st.caption(
    "The original engine's medication, supplement, exercise-modification, and treatment "
    "instructions are intentionally not displayed. This prototype has not been clinically validated."
)
